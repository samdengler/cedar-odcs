"""Unity Catalog to ODCS: the first stage of the build.

Two Unity Catalog API responses go in, one Open Data Contract Standard
document comes out. The table endpoint (GET /api/2.1/unity-catalog/
tables/{full_name}) describes the columns but carries no tags; the
entity tag assignments endpoint (GET /api/2.1/unity-catalog/
entity-tag-assignments/columns/{name}/tags) carries the tags. The
classification, the writer, and the field name all live in column
tags that the data owners set; nothing here is inferred from types
or names.

Column tags read, by key:

  classification     public | internal | confidential | restricted
                     (required: an unclassified column fails the build)
  writer             owner | system | <role name>   (default: system)
  field_name         the API field name, when it is not the camel-cased
                     column name
  cedar_entity_type  marks a column that references a Cedar entity;
                     its value is the entity type (User)

unity/*.json are recorded responses standing in for live API calls.
This module runs at build time only.
"""

import json
import re
from pathlib import Path

import yaml

HERE = Path(__file__).parent

LEVELS = ("public", "internal", "confidential", "restricted")
CONTRACT_VERSION = "v3.2.0"

# Unity type_name to ODCS logicalType.
LOGICAL_TYPES = {
    "STRING": "string",
    "INT": "integer",
    "LONG": "integer",
    "SHORT": "integer",
    "DECIMAL": "number",
    "DOUBLE": "number",
    "FLOAT": "number",
    "BOOLEAN": "boolean",
    "DATE": "date",
    "TIMESTAMP": "timestamp",
}


class ContractError(Exception):
    """The catalog does not say enough to publish the contract."""


def camel(column: str) -> str:
    head, *rest = column.split("_")
    return head + "".join(part.capitalize() for part in rest)


def column_tags(assignments: dict) -> dict:
    """{column name: {tag key: tag value}} from a tag assignments response."""
    tags = {}
    for a in assignments["tag_assignments"]:
        if a["entity_type"] != "columns":
            continue
        column = a["entity_name"].rsplit(".", 1)[1]
        tags.setdefault(column, {})[a["tag_key"]] = a["tag_value"]
    return tags


def property_from_column(column: dict, tags: dict) -> dict:
    name = column["name"]
    level = tags.get("classification")
    if level is None:
        raise ContractError(f"column {name} has no classification tag")
    if level not in LEVELS:
        raise ContractError(f"column {name} has classification {level!r}, not one of {LEVELS}")
    custom = [{"property": "writer", "value": tags.get("writer", "system")}]
    if "cedar_entity_type" in tags:
        custom.append({"property": "cedarEntityType", "value": tags["cedar_entity_type"]})
    prop = {
        "name": tags.get("field_name", camel(name)),
        "physicalName": name,
        "logicalType": LOGICAL_TYPES[column["type_name"]],
        "physicalType": column["type_text"],
        "required": not column["nullable"],
        "classification": level,
        "customProperties": custom,
    }
    if column.get("comment"):
        prop["description"] = column["comment"]
    return prop


def contract_from_unity(table: dict, assignments: dict, entity_name: str, contract_id: str) -> dict:
    """The ODCS document, as a plain dict in the spec's key order."""
    tags = column_tags(assignments)
    properties = [
        property_from_column(c, tags.get(c["name"], {}))
        for c in sorted(table["columns"], key=lambda c: c["position"])
    ]
    host = "dbc-example.cloud.databricks.com"
    return {
        "apiVersion": CONTRACT_VERSION,
        "kind": "DataContract",
        "id": contract_id,
        "name": table["full_name"],
        "version": "1.0.0",
        "status": "active",
        "domain": table["schema_name"],
        "description": {"purpose": table.get("comment", "")},
        "servers": [
            {
                "server": "unity",
                "type": "databricks",
                "host": host,
                "catalog": table["catalog_name"],
                "schema": table["schema_name"],
            }
        ],
        "schema": [
            {
                "name": entity_name,
                "physicalName": table["name"],
                "physicalType": "table",
                "description": table.get("comment", ""),
                "properties": properties,
            }
        ],
        "customProperties": [
            {"property": "sourceCatalog", "value": "unity-catalog"},
            {"property": "sourceTable", "value": table["full_name"]},
        ],
    }


HEADER = (
    "# Generated by unity_import.py from unity/orders.table.json and\n"
    "# unity/orders.column_tags.json at build time. Do not edit; change\n"
    "# the column tags in Unity Catalog and rebuild.\n"
)


def render(contract: dict) -> str:
    return HEADER + yaml.safe_dump(contract, sort_keys=False, allow_unicode=True)


def import_orders() -> str:
    table = json.loads((HERE / "unity/orders.table.json").read_text())
    assignments = json.loads((HERE / "unity/orders.column_tags.json").read_text())
    contract = contract_from_unity(
        table, assignments, entity_name="Order",
        contract_id="7d1d6b2e-2f7a-4d4b-9a1e-3c5e8f0a1b2c",
    )
    return render(contract)
