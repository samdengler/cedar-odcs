"""Role grants rendered to policies: the renderer writes the four field
policies the orders use case writes by hand, and a copy of orders that
carries grants.yaml in place of them passes the orders corpus
unchanged."""

import json
import re
import shutil
from pathlib import Path

import pytest

from cedar_odcs.engine.contract import ContractError, build, write
from cedar_odcs.engine.corpus import case_files, run_case
from cedar_odcs.engine.grants import GrantsError, check_grants, render_grants
from cedar_odcs.engine.usecase import policies_text

ORDERS = Path(__file__).resolve().parents[2] / "usecases/orders"
GRANTS = {
    "reads": {"owner": ["public", "confidential"], "support": ["public", "internal"]},
    "writes": {"owner": "owner", "support": "support"},
}
GRANTS_YAML = """\
reads:
  owner:   [public, confidential]
  support: [public, internal]
writes:
  owner:   owner
  support: support
"""
FIELD_POLICIES = ["customer-fields-on-own-order", "support-fields-on-any-order",
                  "customer-updates-own-order-fields", "support-updates-support-fields"]


def _blocks(text: str) -> dict:
    """@id to the policy's text, comments and blank lines removed."""
    lines = [line for line in text.splitlines() if line.strip() and not line.lstrip().startswith("//")]
    joined = "\n".join(lines) + "\n"
    return {m.group(1): m.group(0) for m in re.finditer(r'@id\("([^"]+)"\)\n.*?\n\};\n', joined, re.S)}


def test_the_rendered_policies_are_the_hand_written_ones():
    rendered = _blocks(render_grants(GRANTS, "Order"))
    written = _blocks((ORDERS / "policies.cedar").read_text())
    assert list(rendered) == FIELD_POLICIES
    for policy_id, text in rendered.items():
        assert text == written[policy_id], policy_id


@pytest.fixture
def orders_with_grants(tmp_path):
    root = tmp_path / "orders"
    shutil.copytree(ORDERS, root, ignore=shutil.ignore_patterns("__pycache__"))
    (root / "contract/grants.yaml").write_text(GRANTS_YAML)
    kept = [text for policy_id, text in _split((root / "policies.cedar").read_text()) if policy_id not in FIELD_POLICIES]
    (root / "policies.cedar").write_text("\n".join(kept))
    write(root, build(root, "Order"))
    return root


def _split(text: str):
    """(@id, text with its leading comment) for each policy, in order."""
    for chunk in re.split(r"\n(?=(?://[^\n]*\n)*@id\()", text):
        m = re.search(r'@id\("([^"]+)"\)', chunk)
        yield (m.group(1) if m else None), chunk


def test_build_writes_the_grants_and_the_corpus_passes_unchanged(orders_with_grants):
    root = orders_with_grants
    assert "support-fields-on-any-order" not in (root / "policies.cedar").read_text()
    assert (root / "contract/generated/grants.cedar").read_text().startswith("// Generated by cedar-odcs build")
    failures = []
    for spec_file in case_files(root):
        spec = json.loads(spec_file.read_text())
        policies = policies_text(root, spec["policies"])
        entities = (root / spec["entities"]).read_text()
        for case in spec["requests"]:
            if not run_case(policies, entities, case).ok:
                failures.append(case["description"])
    assert failures == []


def test_a_grant_to_an_unknown_role_does_not_build(orders_with_grants):
    (orders_with_grants / "contract/grants.yaml").write_text("reads:\n  auditor: [public]\n")
    with pytest.raises(ContractError, match="auditor"):
        build(orders_with_grants, "Order")


def test_levels_and_writer_tags_are_checked():
    with pytest.raises(GrantsError, match="levels"):
        check_grants({"reads": {"owner": ["secret"]}, "writes": {}}, set())
    with pytest.raises(GrantsError, match="writer tag"):
        check_grants({"reads": {}, "writes": {"support": "finance"}}, {"support"})
