"""Role grants rendered to the field-level policies (decision 13).

A use case's field policies are the same four shapes everywhere: a
party reads the fields at some levels, and a party sets the fields
whose writer tag it holds. grants.yaml next to the contract names the
parties and the levels; render_grants writes the policies.

    reads:
      owner:   [public, confidential]     # the acted-for party or the principal
      support: [public, internal]
    writes:
      owner:   owner                       # writer tag a party may set
      support: support

The key `owner` is the ownership form: the resource's `owner`
attribute is the acted-for party when there is one, else the
principal, so an employee acting for a customer holds the customer's
grants. Any other key is a role, in the direct-mode form: `principal
in Role::"<role>"` and no actingFor, so a role's grants are off while
acting for someone. The @id of each policy follows the scheme the
hand-written orders policies use, so corpus cases keep naming them.
"""

from pathlib import Path

import yaml

OWNER = "owner"
LEVELS = {"public", "internal", "confidential", "restricted"}
HEADER = "// Generated by cedar-odcs build from {source}; edit that file, not this one.\n"
OWNERSHIP = "resource.owner == (if context has actingFor then context.actingFor else principal)"


class GrantsError(ValueError):
    pass


def load_grants(path: Path) -> dict:
    grants = yaml.safe_load(Path(path).read_text()) or {}
    if not isinstance(grants, dict) or set(grants) - {"reads", "writes"}:
        raise GrantsError(f"{path}: expected only reads and writes")
    return {"reads": grants.get("reads") or {}, "writes": grants.get("writes") or {}}


def check_grants(grants: dict, roles: set) -> None:
    """Every party is the owner or a known role, every level a known
    level, every writer tag the owner or a known role."""
    for party, levels in grants["reads"].items():
        if party != OWNER and party not in roles:
            raise GrantsError(f"reads: {party!r} is neither owner nor a role")
        if not isinstance(levels, list) or not set(levels) <= LEVELS:
            raise GrantsError(f"reads: {party}: levels {levels!r}; known levels are {sorted(LEVELS)}")
    for party, tag in grants["writes"].items():
        if party != OWNER and party not in roles:
            raise GrantsError(f"writes: {party!r} is neither owner nor a role")
        if tag != OWNER and tag not in roles:
            raise GrantsError(f"writes: {party}: writer tag {tag!r} is neither owner nor a role")


def _policy(policy_id: str, principal: str, action: str, conditions: list) -> str:
    body = " &&\n".join(f"  {c}" for c in conditions)
    return (f'@id("{policy_id}")\npermit(\n  {principal},\n  action == {action},\n  resource\n'
            f') when {{\n{body}\n}};\n')


def render_grants(grants: dict, entity_name: str,
                  read_field_action: str = None, write_field_action: str = None) -> str:
    """The Cedar text of the field policies grants.yaml names: reads,
    then writes, each in the file's order."""
    entity = entity_name.lower()
    read_action = read_field_action or f'Action::"Read{entity_name}Field"'
    write_action = write_field_action or f'Action::"Update{entity_name}Field"'
    levels_tag = f'Contract::"{entity_name}"'
    writers_tag = f'Contract::"{entity_name}/writers"'
    out = []
    for party, levels in grants["reads"].items():
        listed = ", ".join(f'"{level}"' for level in levels)
        field = ["context has field", f"{levels_tag}.hasTag(context.field)",
                 f"[{listed}].contains({levels_tag}.getTag(context.field))"]
        if party == OWNER:
            out.append(_policy(f"customer-fields-on-own-{entity}", "principal", read_action,
                               ["resource has owner", OWNERSHIP] + field))
        else:
            out.append(_policy(f"{party}-fields-on-any-{entity}", f'principal in Role::"{party}"', read_action,
                               ["!(context has actingFor)"] + field))
    for party, tag in grants["writes"].items():
        field = ["context has field", f"{writers_tag}.hasTag(context.field)",
                 f'{writers_tag}.getTag(context.field) == "{tag}"']
        if party == OWNER:
            out.append(_policy(f"customer-updates-own-{entity}-fields", "principal", write_action,
                               ["resource has owner", OWNERSHIP] + field))
        else:
            out.append(_policy(f"{party}-updates-{tag}-fields", f'principal in Role::"{party}"', write_action,
                               ["!(context has actingFor)"] + field))
    return "\n".join(out)
